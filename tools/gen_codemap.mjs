// Bundle reference/model.py into src/generated/model_py.js so the browser can
// show the real source without fetching files.   node tools/gen_codemap.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(root, 'reference', 'model.py'), 'utf8');
const out = `// Generated by tools/gen_codemap.mjs from reference/model.py. Do not edit.\nexport const MODEL_PY = ${JSON.stringify(src)};\n`;
const target = join(root, 'src', 'generated', 'model_py.js');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== out) { console.error('Embedded model.py is stale. Run node tools/gen_codemap.mjs.'); process.exitCode = 1; }
  else console.log('Embedded model.py matches the reference.');
} else {
  writeFileSync(target, out);
  console.log(`wrote src/generated/model_py.js (${src.split('\n').length} lines)`);
}
